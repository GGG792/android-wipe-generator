// ===== Syntax Highlight & Render =====
function renderOutput(code) {
  const esc = escapeHtml(code);
  // 逐行高亮
  const highlighted = esc.split('\n').map(line => highlightLine(line)).join('\n');
  document.getElementById('outputArea').innerHTML = '<code class="language-bash">' + highlighted + '</code>';
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function highlightLine(line) {
  // 注释
  if (/^\s*#/.test(line)) {
    return '<span class="tok-comment">' + escapeHtml(line) + '</span>';
  }
  let out = escapeHtml(line);
  // 字符串
  out = out.replace(/(&quot;|")([^"&]*)(")/g, '<span class="tok-string">"$2"</span>');
  // echo 等命令
  out = out.replace(/\b(echo|rm|read|exit|id|tee|mktemp|chmod|base64|openssl|sleep)\b/g, '<span class="tok-command">$1</span>');
  // 变量
  out = out.replace(/\$[A-Za-z_][A-Za-z0-9_]*/g, '<span class="tok-var">$&</span>');
  // 关键字
  out = out.replace(/\b(if|then|else|fi|for|in|do|done|while|case|esac|break|continue|exit)\b/g, '<span class="tok-keyword">$1</span>');
  return out;
}

// ===== Copy & Download =====
function copyOutput() {
  if (!lastGeneratedScript) {
    alert('请先生成脚本！');
    return;
  }
  navigator.clipboard.writeText(lastGeneratedScript).then(() => {
    alert('已复制到剪贴板！');
  }).catch(() => {
    // fallback
    const ta = document.createElement('textarea');
    ta.value = lastGeneratedScript;
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
    alert('已复制到剪贴板！');
  });
}

function downloadSh() {
  if (!lastGeneratedScript) {
    alert('请先生成脚本！');
    return;
  }
  const blob = new Blob([lastGeneratedScript], { type: 'text/x-sh' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'android_wipe_' + Date.now() + '.sh';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
