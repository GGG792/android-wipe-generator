let lastGeneratedScript = '';

function getSelectedDirs() {
  const checked = document.querySelectorAll('#dirList input[type="checkbox"]:checked');
  return Array.from(checked).map(cb => cb.value);
}

function generate() {
  const banner = document.getElementById('bannerTitle').value.trim();
  const mode = document.getElementById('encryptMode').value;
  const dirs = getSelectedDirs();
  const selfDel = document.getElementById('selfDelete').checked;

  if (dirs.length === 0) {
    alert('请至少选择一个要清理的目录！');
    return;
  }

  let script = buildBaseScript(banner, dirs, selfDel);

  // 根据打包方案包装
  if (mode === 'makeself') {
    script = wrapMakeself(script);
  } else if (mode === 'openssl') {
    script = wrapOpenSSL(script);
  } else if (mode === 'shc') {
    script = wrapShc(script);
  }

  lastGeneratedScript = script;
  renderOutput(script);
}

